export function getCoordsMunicipio(departamento, municipio) {
  const direct = MUNICIPIO_COORDS[`${departamento}|${municipio}`]
  if (direct) return direct
  const capital = CAPITAL_POR_DEPARTAMENTO[departamento]
  if (capital) return MUNICIPIO_COORDS[`${departamento}|${capital}`] || null
  return null
}

// Sin esto, escribir "apartado"/"chigorodo" (sin tilde, lo normal al
// escribir rapido en el telefono) no matcheaba "Apartado"/"Chigorodo".
export function normalize(s) {
  return s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase()
}

export function distanciaKm(lat1, lng1, lat2, lng2) {
  const R = 6371
  const dLat = (lat2 - lat1) * Math.PI / 180
  const dLng = (lng2 - lng1) * Math.PI / 180
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * Math.sin(dLng / 2) ** 2
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
}

// Busca un nombre de ciudad (tal como lo reporta el header de
// geolocalización por IP de Vercel, x-vercel-ip-city) contra los ~1120
// municipios reales del país — a diferencia de MUNICIPIO_COORDS (que solo
// cubre 81 puntos con coordenadas propias), esto reconoce CUALQUIER
// municipio colombiano por nombre, con o sin coordenadas precisas.
// Devuelve { departamento, municipio } o null.
let _municipioIndexNorm = null
export function municipioDesdeNombreIP(nombreCiudad) {
  if (!nombreCiudad) return null
  if (!_municipioIndexNorm) {
    _municipioIndexNorm = new Map()
    for (const [dept, lista] of Object.entries(MUNICIPIOS_POR_DEPARTAMENTO)) {
      for (const muni of lista) {
        const key = normalize(muni)
        // Si el mismo nombre de municipio existe en varios departamentos,
        // se queda con el primero — es un desempate razonable para una
        // sugerencia silenciosa (no bloquea nada, el visitante igual puede
        // escribir su ciudad manualmente).
        if (!_municipioIndexNorm.has(key)) _municipioIndexNorm.set(key, { departamento: dept, municipio: muni })
      }
    }
  }
  return _municipioIndexNorm.get(normalize(nombreCiudad)) || null
}

// Municipio con coordenadas propias mas cercano a un punto lat/lng
// (capitales + satelites de area metropolitana). Devuelve
// { departamento, municipio } o null.
export function municipioMasCercanoNacional(lat, lng) {
  let mejor = null
  let mejorDist = Infinity
  for (const [key, c] of Object.entries(MUNICIPIO_COORDS)) {
    const d = distanciaKm(lat, lng, c.lat, c.lng)
    if (d < mejorDist) {
      mejorDist = d
      const [departamento, municipio] = key.split('|')
      mejor = { departamento, municipio }
    }
  }
  return mejor
}
